create or replace function public.save_form_draft(p_definition jsonb)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  source_id text;
  existing_form public.form_definitions%rowtype;
  saved_form public.form_definitions%rowtype;
begin
  if caller_id is null then raise exception 'Authentication is required to save a form.'; end if;
  if not public.authorization_user_has_capability(caller_id, 'form.create') then
    raise exception 'Your assigned roles cannot create or edit forms.';
  end if;
  if coalesce(jsonb_typeof(p_definition), '') <> 'object'
    or coalesce(jsonb_typeof(p_definition -> 'blocks'), '') <> 'array'
    or coalesce(p_definition ->> 'version', '') !~ '^[1-9][0-9]*$'
  then
    raise exception 'A valid form definition is required.';
  end if;
  source_id := btrim(coalesce(p_definition ->> 'id', ''));
  if source_id = '' then raise exception 'The form ID is required.'; end if;

  select * into existing_form
  from public.form_definitions
  where id = source_id;
  if found then
    if existing_form.owner_id <> caller_id then raise exception 'This form belongs to another author.'; end if;
    if existing_form.status = 'archived' then
      raise exception 'Archived forms cannot be overwritten. Open the form as a copy instead.';
    end if;
    if existing_form.review_status <> 'draft' then
      raise exception 'A form under review or already published cannot be overwritten. Open it as a copy instead.';
    end if;
  end if;

  insert into public.form_definitions (
    id, owner_id, status, review_status, visibility, publication_mode,
    schema_version, title, definition, archived_at, published_by, published_at
  ) values (
    source_id, caller_id, 'active', 'draft', 'private', 'private',
    (p_definition ->> 'version')::integer,
    coalesce(p_definition #>> '{meta,title}', ''),
    p_definition, null, null, null
  )
  on conflict (id) do update set
    status = 'active',
    schema_version = excluded.schema_version,
    title = excluded.title,
    definition = excluded.definition,
    archived_at = null
  returning * into saved_form;

  return jsonb_build_object(
    'id', saved_form.id,
    'owner_id', saved_form.owner_id,
    'status', saved_form.status,
    'review_status', saved_form.review_status,
    'visibility', saved_form.visibility,
    'publication_mode', saved_form.publication_mode,
    'published_by', saved_form.published_by,
    'published_at', saved_form.published_at,
    'created_at', saved_form.created_at,
    'updated_at', saved_form.updated_at,
    'archived_at', saved_form.archived_at,
    'definition', saved_form.definition
  );
end;
$$;

create or replace function public.submit_form_for_review(p_form_id text)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  source_form public.form_definitions%rowtype;
  submitted_form public.form_definitions%rowtype;
begin
  if caller_id is null then raise exception 'Authentication is required to submit a form.'; end if;
  if not public.authorization_user_has_capability(caller_id, 'form.submit_review') then
    raise exception 'Your assigned roles cannot submit forms for review.';
  end if;
  select * into source_form
  from public.form_definitions
  where id = btrim(coalesce(p_form_id, ''))
  for update;
  if not found then raise exception 'The form could not be found.'; end if;
  if source_form.owner_id <> caller_id then raise exception 'This form belongs to another author.'; end if;
  if source_form.status <> 'active'
    or source_form.review_status <> 'draft'
    or source_form.visibility <> 'private'
  then
    raise exception 'Only an active private draft can be submitted for review.';
  end if;
  if not exists (
    select 1 from jsonb_array_elements(source_form.definition -> 'blocks') block
    where block ->> 'kind' = 'question'
  ) then
    raise exception 'Add at least one question before submitting this form.';
  end if;

  update public.form_definitions
  set review_status = 'pending_review', visibility = 'private'
  where id = source_form.id
  returning * into submitted_form;
  return to_jsonb(submitted_form);
end;
$$;

create or replace function public.review_form(
  p_form_id text,
  p_decision text,
  p_notes text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  normalized_decision text := lower(btrim(coalesce(p_decision, '')));
  normalized_notes text := btrim(coalesce(p_notes, ''));
  source_form public.form_definitions%rowtype;
  reviewed_form public.form_definitions%rowtype;
  review_record public.form_reviews%rowtype;
  next_visibility text;
begin
  if caller_id is null then raise exception 'Authentication is required to review a form.'; end if;
  if not public.authorization_user_has_capability(caller_id, 'form.review') then
    raise exception 'Your assigned roles cannot review forms.';
  end if;
  if normalized_decision not in ('approved', 'changes_requested', 'rejected') then
    raise exception 'The form review decision is invalid.';
  end if;
  if normalized_decision <> 'approved' and normalized_notes = '' then
    raise exception 'Review notes are required when requesting changes or rejecting a form.';
  end if;

  select * into source_form
  from public.form_definitions
  where id = btrim(coalesce(p_form_id, ''))
  for update;
  if not found then raise exception 'The form could not be found.'; end if;
  if source_form.owner_id = caller_id then
    raise exception 'A submitted form must be reviewed by a different mentor or administrator.';
  end if;
  if source_form.status <> 'active' or source_form.review_status <> 'pending_review' then
    raise exception 'Only a form awaiting review can receive a decision.';
  end if;

  next_visibility := case when normalized_decision = 'approved' then 'public' else 'private' end;
  update public.form_definitions
  set review_status = normalized_decision, visibility = next_visibility
  where id = source_form.id
  returning * into reviewed_form;

  insert into public.form_reviews (
    form_id, owner_id, reviewer_id, decision, notes, reviewed_at
  ) values (
    source_form.id, source_form.owner_id, caller_id,
    normalized_decision, normalized_notes, reviewed_form.updated_at
  ) returning * into review_record;

  if normalized_decision = 'approved' then
    insert into public.content_publication_events (
      resource_type, resource_id, owner_id, actor_id, publication_mode, notes, published_at
    ) values (
      'form', source_form.id, source_form.owner_id, caller_id,
      'review_approved', normalized_notes, reviewed_form.published_at
    );
  end if;
  return jsonb_build_object('form', to_jsonb(reviewed_form), 'review', to_jsonb(review_record));
end;
$$;

