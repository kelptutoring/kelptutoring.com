  new.schema_version := definition_version;
  new.title := coalesce(new.definition #>> '{meta,title}', '');
  caller_is_reviewer := public.authorization_user_has_capability(caller_id, 'form.review');
  caller_can_publish := public.authorization_user_has_capability(caller_id, 'form.publish');

  if tg_op = 'INSERT' then
    if new.status <> 'active'
      or new.review_status <> 'draft'
      or new.visibility <> 'private'
      or new.publication_mode <> 'private'
    then
      raise exception 'New forms must begin as private drafts.';
    end if;
    new.created_at := transition_time;
    new.updated_at := new.created_at;
    new.archived_at := null;
    new.publication_mode := 'private';
    new.published_by := null;
    new.published_at := null;
    return new;
  end if;

  if new.id is distinct from old.id
    or new.owner_id is distinct from old.owner_id
