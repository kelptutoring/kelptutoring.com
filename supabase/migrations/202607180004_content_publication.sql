    if old.review_status <> 'draft' then
      raise exception 'A form under review or already published cannot be overwritten.';
    end if;
    if exists (
      select 1 from public.form_submissions
      where form_owner_id = old.owner_id and form_id = old.id
    ) then
      raise exception 'Forms with submissions cannot be overwritten. Open the form as a copy instead.';
    end if;
  end if;

  new.updated_at := transition_time;
  if new.status = 'archived' then new.archived_at := new.updated_at;
  else new.archived_at := null;
  end if;
  return new;
end;
