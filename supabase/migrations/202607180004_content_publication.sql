returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  normalized_decision text := lower(btrim(coalesce(p_decision, '')));
  normalized_notes text := btrim(coalesce(p_notes, ''));
  source_exam public.exam_definitions%rowtype;
  reviewed_exam public.exam_definitions%rowtype;
  review_record public.exam_reviews%rowtype;
  trusted_bundle jsonb;
  next_visibility text;
begin
  if caller_id is null then raise exception 'Authentication is required to review an exam.'; end if;
  if not public.authorization_user_has_capability(caller_id, 'exam.review') then
    raise exception 'Your assigned roles cannot review exams.';
  end if;
  if normalized_decision not in ('approved', 'changes_requested', 'rejected') then
    raise exception 'The exam review decision is invalid.';
  end if;
  if normalized_decision <> 'approved' and normalized_notes = '' then
    raise exception 'Review notes are required when requesting changes or rejecting an exam.';
  end if;

  select * into source_exam
  from public.exam_definitions
  where id = btrim(coalesce(p_exam_id, ''))
  for update;
  if not found then raise exception 'The exam could not be found.'; end if;
  if source_exam.owner_id = caller_id then
    raise exception 'A submitted exam must be reviewed by a different mentor or administrator.';
  end if;
  if source_exam.status <> 'active' or source_exam.review_status <> 'pending_review' then
    raise exception 'Only an exam awaiting review can receive a decision.';
  end if;

  next_visibility := case when normalized_decision = 'approved' then 'public' else 'private' end;
  trusted_bundle := public.set_exam_bundle_review_state(
    source_exam.bundle, normalized_decision, next_visibility, normalized_decision = 'approved'
  );
  update public.exam_definitions
  set review_status = normalized_decision, visibility = next_visibility, bundle = trusted_bundle
  where id = source_exam.id
  returning * into reviewed_exam;

  update public.exam_questions
  set review_status = normalized_decision,
      classification_status = case when normalized_decision = 'approved' then 'reviewed' else classification_status end,
      content = case
        when normalized_decision = 'approved'
          then jsonb_set(content, '{classificationStatus}', to_jsonb('reviewed'::text), true)
        else content
      end,
      updated_at = reviewed_exam.updated_at
  where exam_id = source_exam.id;

  insert into public.exam_reviews (
    exam_id, owner_id, reviewer_id, decision, notes, reviewed_at
  ) values (
    source_exam.id, source_exam.owner_id, caller_id,
    normalized_decision, normalized_notes, reviewed_exam.updated_at
  ) returning * into review_record;

  if normalized_decision = 'approved' then
    insert into public.content_publication_events (
      resource_type, resource_id, owner_id, actor_id, publication_mode, notes, published_at
    ) values (
      'exam', source_exam.id, source_exam.owner_id, caller_id,
      'review_approved', normalized_notes, reviewed_exam.published_at
    );
  end if;
  return jsonb_build_object('exam', to_jsonb(reviewed_exam), 'review', to_jsonb(review_record));
end;
$$;

create or replace function public.publish_exam(
  p_exam_id text,
  p_notes text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  source_exam public.exam_definitions%rowtype;
  published_exam public.exam_definitions%rowtype;
  trusted_bundle jsonb;
  normalized_notes text := btrim(coalesce(p_notes, ''));
begin
  if caller_id is null then raise exception 'Authentication is required to publish an exam.'; end if;
  if not public.authorization_user_has_capability(caller_id, 'exam.publish') then
    raise exception 'Only a mentor or administrator can publish an exam directly.';
  end if;
  select * into source_exam
  from public.exam_definitions
  where id = btrim(coalesce(p_exam_id, ''))
  for update;
  if not found then raise exception 'The exam could not be found.'; end if;
  if source_exam.owner_id <> caller_id then raise exception 'Only the exam owner can publish this draft directly.'; end if;
  if source_exam.status <> 'active'
    or source_exam.review_status <> 'draft'
    or source_exam.visibility <> 'private'
  then
    raise exception 'Only an active private draft can be published directly.';
  end if;
  if not exists (select 1 from public.exam_questions where exam_id = source_exam.id) then
    raise exception 'Add at least one question before publishing this exam.';
  end if;
  if exists (
    select 1 from public.exam_questions
    where exam_id = source_exam.id and difficulty = 'unclassified'
  ) then
    raise exception 'Classify every question before publishing this exam.';
  end if;

  trusted_bundle := public.set_exam_bundle_review_state(
    source_exam.bundle, 'approved', 'public', true
  );
  update public.exam_definitions
  set review_status = 'approved', visibility = 'public', bundle = trusted_bundle
  where id = source_exam.id
  returning * into published_exam;
  update public.exam_questions
  set review_status = 'approved',
      classification_status = 'reviewed',
      content = jsonb_set(content, '{classificationStatus}', to_jsonb('reviewed'::text), true),
      updated_at = published_exam.updated_at
  where exam_id = source_exam.id;
  insert into public.content_publication_events (
    resource_type, resource_id, owner_id, actor_id, publication_mode, notes, published_at
  ) values (
    'exam', source_exam.id, source_exam.owner_id, caller_id,
    'privileged_direct', normalized_notes, published_exam.published_at
  );
  return to_jsonb(published_exam);
end;
$$;

