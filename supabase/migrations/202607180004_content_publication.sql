set publication_mode = case
      when definition.review_status = 'approved' and definition.visibility = 'public'
        then 'review_approved'
      else 'private'
    end,
    published_by = case
      when definition.review_status = 'approved' and definition.visibility = 'public'
        then coalesce((
          select reviews.reviewer_id
          from public.exam_reviews reviews
          where reviews.exam_id = definition.id and reviews.decision = 'approved'
          order by reviews.reviewed_at desc
          limit 1
        ), definition.owner_id)
      else null
    end,
    published_at = case
      when definition.review_status = 'approved' and definition.visibility = 'public'
        then definition.updated_at
      else null
    end;

