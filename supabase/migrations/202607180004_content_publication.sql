create or replace function public.enforce_exam_definition_lifecycle()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  caller_is_reviewer boolean := false;
  caller_can_publish boolean := false;
  state_transition_allowed boolean := false;
  transition_time timestamptz := clock_timestamp();
begin
  caller_is_reviewer := public.authorization_user_has_capability(caller_id, 'exam.review');
  caller_can_publish := public.authorization_user_has_capability(caller_id, 'exam.publish');

  if tg_op = 'INSERT' then
    if new.status <> 'active'
      or new.review_status <> 'draft'
      or new.visibility <> 'private'
      or new.publication_mode <> 'private'
    then
      raise exception 'New exams must begin as private drafts.';
    end if;
    new.created_at := coalesce(new.created_at, transition_time);
    new.updated_at := new.created_at;
    new.archived_at := null;
    new.publication_mode := 'private';
    new.published_by := null;
    new.published_at := null;
    return new;
  end if;

  if new.id is distinct from old.id
    or new.owner_id is distinct from old.owner_id
    or new.created_at is distinct from old.created_at
  then
    raise exception 'Exam identity and ownership fields are immutable.';
  end if;
  if old.status = 'archived' then
    raise exception 'Archived exams cannot be overwritten. Open the exam as a copy instead.';
  end if;

  if new.review_status is distinct from old.review_status
    or new.visibility is distinct from old.visibility
  then
    if old.review_status = 'draft'
      and new.review_status = 'pending_review'
      and new.visibility = 'private'
      and caller_id = old.owner_id
      and public.authorization_user_has_capability(caller_id, 'exam.submit_review')
    then
      state_transition_allowed := true;
      new.publication_mode := 'private';
      new.published_by := null;
      new.published_at := null;
    elsif old.review_status = 'pending_review'
      and new.review_status in ('approved', 'changes_requested', 'rejected')
      and new.visibility = (case when new.review_status = 'approved' then 'public' else 'private' end)
      and caller_is_reviewer
    then
      state_transition_allowed := true;
      if new.review_status = 'approved' then
        new.publication_mode := 'review_approved';
        new.published_by := caller_id;
        new.published_at := transition_time;
      else
        new.publication_mode := 'private';
        new.published_by := null;
        new.published_at := null;
      end if;
    elsif old.review_status = 'draft'
      and new.review_status = 'approved'
      and new.visibility = 'public'
      and caller_id = old.owner_id
      and caller_can_publish
    then
      state_transition_allowed := true;
      new.publication_mode := 'privileged_direct';
      new.published_by := caller_id;
      new.published_at := transition_time;
    else
      raise exception 'The requested exam publication transition is not permitted.';
    end if;
  elsif new.publication_mode is distinct from old.publication_mode
    or new.published_by is distinct from old.published_by
    or new.published_at is distinct from old.published_at
  then
    raise exception 'Exam publication metadata is server-owned.';
  end if;

  if new.status = 'archived' then
    if old.review_status <> 'draft'
      or new.review_status <> 'draft'
      or new.visibility <> 'private'
      or new.publication_mode <> 'private'
      or new.bundle is distinct from old.bundle
    then
      raise exception 'Only the unchanged private draft can be archived.';
    end if;
  elsif new.status <> 'active' then
    raise exception 'The requested exam lifecycle transition is invalid.';
  end if;

  if new.bundle is distinct from old.bundle
    and old.review_status <> 'draft'
    and not state_transition_allowed
  then
    raise exception 'An exam under review or already published cannot be overwritten.';
  end if;

  new.updated_at := transition_time;
  if new.status = 'archived' then new.archived_at := new.updated_at;
  else new.archived_at := null;
  end if;
  return new;
end;
$$;

create or replace function public.enforce_form_definition_lifecycle()
returns trigger
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  definition_version integer;
  caller_is_reviewer boolean := false;
  caller_can_publish boolean := false;
  state_transition_allowed boolean := false;
  transition_time timestamptz := clock_timestamp();
begin
  if jsonb_typeof(new.definition) <> 'object'
