create or replace function public.get_my_authorization()
returns jsonb
language plpgsql
stable
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  role_keys text[] := array[]::text[];
  capability_keys text[] := array[]::text[];
  primary_role text;
begin
  if caller_id is null then
    raise exception 'Authentication is required to load authorization.';
  end if;

  select coalesce(array_agg(ur.role_key order by ar.sort_order, ur.role_key), array[]::text[])
  into role_keys
  from public.user_roles ur
  join public.authorization_roles ar on ar.role_key = ur.role_key
  where ur.user_id = caller_id and ur.status = 'active';

  select ur.role_key
  into primary_role
  from public.user_roles ur
  join public.authorization_roles ar on ar.role_key = ur.role_key
  where ur.user_id = caller_id and ur.status = 'active'
  order by ur.is_primary desc, ar.sort_order, ur.role_key
  limit 1;

  if coalesce(cardinality(role_keys), 0) = 0 then
    select role into primary_role from public.profiles where id = caller_id;
    role_keys := array[coalesce(primary_role, 'student')];
  end if;

  select coalesce(array_agg(distinct rc.capability_key order by rc.capability_key), array[]::text[])
  into capability_keys
  from public.role_capabilities rc
  where rc.role_key = any(role_keys);

  return jsonb_build_object(
    'version', 1,
    'primaryRole', coalesce(primary_role, role_keys[1], 'student'),
    'roles', to_jsonb(role_keys),
    'capabilities', to_jsonb(capability_keys)
  );
end;
$$;

create or replace function public.set_my_primary_role(p_role_key text)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  normalized_role text := lower(btrim(coalesce(p_role_key, '')));
begin
  if caller_id is null then raise exception 'Authentication is required.'; end if;
  if not exists (
    select 1 from public.user_roles
    where user_id = caller_id and role_key = normalized_role and status = 'active'
  ) then
    raise exception 'The selected workspace role is not assigned to this user.';
  end if;

  update public.user_roles set is_primary = false
  where user_id = caller_id and status = 'active' and is_primary;
  update public.user_roles set is_primary = true
  where user_id = caller_id and role_key = normalized_role and status = 'active';
  update public.profiles set role = normalized_role where id = caller_id;
  insert into public.authorization_events (
    target_user_id, actor_user_id, role_key, event_type
  ) values (caller_id, caller_id, normalized_role, 'primary_selected');
  return public.get_my_authorization();
end;
$$;

create or replace function public.grant_user_role(
  p_user_id uuid,
  p_role_key text,
  p_reason text default '',
  p_make_primary boolean default false
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  normalized_role text := lower(btrim(coalesce(p_role_key, '')));
  prior_status text;
  should_be_primary boolean := coalesce(p_make_primary, false);
begin
  if caller_id is null or not public.authorization_user_has_capability(caller_id, 'authorization.manage') then
    raise exception 'Only an authorization administrator can grant roles.';
  end if;
  if not exists (select 1 from public.profiles where id = p_user_id) then
    raise exception 'The target user profile does not exist.';
  end if;
  if not exists (select 1 from public.authorization_roles where role_key = normalized_role) then
    raise exception 'The requested role does not exist.';
  end if;

  select status into prior_status from public.user_roles
  where user_id = p_user_id and role_key = normalized_role;
  if not exists (
    select 1 from public.user_roles
    where user_id = p_user_id and status = 'active' and is_primary
  ) then
    should_be_primary := true;
  end if;
  if should_be_primary then
    update public.user_roles set is_primary = false
    where user_id = p_user_id and status = 'active' and is_primary;
  end if;

  insert into public.user_roles (
    user_id, role_key, status, is_primary, source, granted_by, granted_at,
    revoked_by, revoked_at
  ) values (
    p_user_id, normalized_role, 'active', should_be_primary, 'admin', caller_id,
    clock_timestamp(), null, null
  )
  on conflict (user_id, role_key) do update set
    status = 'active',
    is_primary = excluded.is_primary or public.user_roles.is_primary,
    source = 'admin',
    granted_by = caller_id,
    granted_at = clock_timestamp(),
    revoked_by = null,
    revoked_at = null;

  if should_be_primary then
    update public.profiles set role = normalized_role where id = p_user_id;
  end if;
  insert into public.authorization_events (
    target_user_id, actor_user_id, role_key, event_type, reason
  ) values (
    p_user_id, caller_id, normalized_role,
    case when prior_status = 'revoked' then 'regranted' else 'granted' end,
    btrim(coalesce(p_reason, ''))
  );
  return jsonb_build_object('userId', p_user_id, 'role', normalized_role, 'status', 'active');
end;
$$;

create or replace function public.revoke_user_role(
  p_user_id uuid,
  p_role_key text,
  p_reason text default ''
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  caller_id uuid := auth.uid();
  normalized_role text := lower(btrim(coalesce(p_role_key, '')));
  was_primary boolean := false;
  replacement_role text;
begin
  if caller_id is null or not public.authorization_user_has_capability(caller_id, 'authorization.manage') then
    raise exception 'Only an authorization administrator can revoke roles.';
  end if;
  select is_primary into was_primary
  from public.user_roles
  where user_id = p_user_id and role_key = normalized_role and status = 'active';
  if not found then raise exception 'The target user does not have this active role.'; end if;
  if (select count(*) from public.user_roles where user_id = p_user_id and status = 'active') <= 1 then
    raise exception 'A user must retain at least one active role.';
  end if;

  update public.user_roles set
    status = 'revoked', is_primary = false, revoked_by = caller_id,
    revoked_at = clock_timestamp()
  where user_id = p_user_id and role_key = normalized_role;

  if was_primary then
    select ur.role_key into replacement_role
    from public.user_roles ur
    join public.authorization_roles ar on ar.role_key = ur.role_key
    where ur.user_id = p_user_id and ur.status = 'active'
    order by ar.sort_order, ur.role_key
    limit 1;
    update public.user_roles set is_primary = true
    where user_id = p_user_id and role_key = replacement_role;
    update public.profiles set role = replacement_role where id = p_user_id;
  end if;

  insert into public.authorization_events (
    target_user_id, actor_user_id, role_key, event_type, reason
  ) values (
    p_user_id, caller_id, normalized_role, 'revoked', btrim(coalesce(p_reason, ''))
  );
  return jsonb_build_object('userId', p_user_id, 'role', normalized_role, 'status', 'revoked');
end;
$$;

-- One service-role-only recovery path establishes the first administrator
-- after public sign-up has created a student profile. The function refuses to
-- run once any active administrator exists and records the trusted bootstrap.
create or replace function public.bootstrap_first_administrator(
  p_user_id uuid,
  p_reason text default 'Initial trusted administrator bootstrap'
)
returns jsonb
language plpgsql
security definer
set search_path = pg_catalog, public
as $$
declare
  prior_status text;
begin
  if coalesce(auth.role(), '') <> 'service_role' then
    raise exception 'The first administrator can only be bootstrapped by the service role.';
  end if;

  -- Serialize the one-time check so concurrent trusted bootstrap requests
  -- cannot both observe an empty administrator set.
  perform pg_advisory_xact_lock(hashtext('public.bootstrap_first_administrator'));

  if p_user_id is null or not exists (
    select 1 from public.profiles where id = p_user_id
  ) then
    raise exception 'The bootstrap target profile does not exist.';
  end if;
  if exists (
    select 1 from public.user_roles
    where role_key = 'admin' and status = 'active'
  ) then
    raise exception 'An active administrator already exists.';
  end if;

  select status into prior_status
  from public.user_roles
  where user_id = p_user_id and role_key = 'admin';

  update public.user_roles
  set is_primary = false
  where user_id = p_user_id and status = 'active' and is_primary;

  insert into public.user_roles (
    user_id, role_key, status, is_primary, source, granted_by, granted_at,
    revoked_by, revoked_at, metadata
  ) values (
    p_user_id, 'admin', 'active', true, 'system', null, clock_timestamp(),
    null, null, jsonb_build_object('bootstrap', true, 'trustedRole', 'service_role')
  )
  on conflict (user_id, role_key) do update set
    status = 'active',
    is_primary = true,
    source = 'system',
    granted_by = null,
    granted_at = clock_timestamp(),
    revoked_by = null,
    revoked_at = null,
    metadata = jsonb_build_object('bootstrap', true, 'trustedRole', 'service_role');

  update public.profiles set role = 'admin' where id = p_user_id;

  insert into public.authorization_events (
    target_user_id, actor_user_id, role_key, event_type, reason, metadata
  ) values (
    p_user_id,
    auth.uid(),
    'admin',
    case when prior_status = 'revoked' then 'regranted' else 'granted' end,
    btrim(coalesce(p_reason, '')),
    jsonb_build_object('bootstrap', true, 'trustedRole', 'service_role')
  );

  return jsonb_build_object(
    'userId', p_user_id,
    'role', 'admin',
    'status', 'active',
    'primary', true,
    'bootstrap', true
  );
end;
$$;

