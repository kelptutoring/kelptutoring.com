-- profiles.role remains a temporary primary-workspace hint only.

create table if not exists public.authorization_roles (
  role_key text primary key,
  display_name text not null,
  description text not null default '',
  sort_order integer not null default 100,
  is_system boolean not null default true,
  created_at timestamptz not null default now(),
  constraint authorization_roles_key_check check (
    role_key ~ '^[a-z][a-z0-9._-]{0,95}$'
  )
);

create table if not exists public.authorization_capabilities (
  capability_key text primary key,
  description text not null default '',
  created_at timestamptz not null default now(),
  constraint authorization_capabilities_key_check check (
    capability_key ~ '^[a-z][a-z0-9._-]{0,95}$'
  )
);

create table if not exists public.role_capabilities (
  role_key text not null references public.authorization_roles(role_key) on delete cascade,
  capability_key text not null references public.authorization_capabilities(capability_key) on delete cascade,
  granted_at timestamptz not null default now(),
  primary key (role_key, capability_key)
);

create table if not exists public.user_roles (
  user_id uuid not null references public.profiles(id) on delete cascade,
  role_key text not null references public.authorization_roles(role_key),
  status text not null default 'active',
  is_primary boolean not null default false,
  source text not null default 'admin',
  granted_by uuid,
  granted_at timestamptz not null default now(),
  revoked_by uuid,
  revoked_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  primary key (user_id, role_key),
  constraint user_roles_status_check check (status in ('active', 'revoked')),
  constraint user_roles_source_check check (source in ('legacy', 'signup', 'admin', 'credential', 'system')),
  constraint user_roles_metadata_check check (jsonb_typeof(metadata) = 'object'),
  constraint user_roles_revocation_check check (
    (status = 'active' and revoked_at is null and revoked_by is null)
    or (status = 'revoked' and revoked_at is not null)
  )
);

create unique index if not exists user_roles_one_primary_idx
on public.user_roles (user_id)
where status = 'active' and is_primary;

create index if not exists user_roles_active_role_idx
on public.user_roles (role_key, user_id)
where status = 'active';

create table if not exists public.user_credentials (
  id bigint generated by default as identity primary key,
  user_id uuid not null references public.profiles(id) on delete cascade,
  credential_type text not null,
  title text not null default '',
  field_of_study text not null default '',
  institution text not null default '',
  country text not null default '',
  verification_status text not null default 'pending',
  evidence_reference text,
  submitted_at timestamptz not null default now(),
  reviewed_by uuid,
  reviewed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  constraint user_credentials_type_present check (btrim(credential_type) <> ''),
  constraint user_credentials_status_check check (
    verification_status in ('pending', 'verified', 'rejected', 'expired')
  ),
  constraint user_credentials_review_check check (
    (verification_status = 'pending' and reviewed_by is null and reviewed_at is null)
    or (verification_status <> 'pending' and reviewed_by is not null and reviewed_at is not null)
  ),
  constraint user_credentials_metadata_check check (jsonb_typeof(metadata) = 'object')
);

create index if not exists user_credentials_user_status_idx
on public.user_credentials (user_id, verification_status, submitted_at desc);

create table if not exists public.authorization_events (
  id bigint generated by default as identity primary key,
  target_user_id uuid not null,
  actor_user_id uuid,
  role_key text not null,
  event_type text not null,
  reason text not null default '',
  occurred_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  constraint authorization_events_role_present check (btrim(role_key) <> ''),
  constraint authorization_events_type_check check (
    event_type in ('granted', 'regranted', 'revoked', 'primary_selected')
  ),
  constraint authorization_events_metadata_check check (jsonb_typeof(metadata) = 'object')
);

create index if not exists authorization_events_target_idx
on public.authorization_events (target_user_id, occurred_at desc);

